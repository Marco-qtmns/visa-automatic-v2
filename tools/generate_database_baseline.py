"""Generate the reviewed, explicit Alembic baseline from ORM metadata.

This is a development-time code generator only.  The generated migration is a
version-frozen list of ``op.create_table``/``op.create_index`` calls and never
imports application models when Alembic executes it.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from alembic.autogenerate import render_python_code
from alembic.migration import MigrationContext
from alembic.operations import ops

from backend.app.database import Base
from backend.app.models import *  # noqa: F401,F403


REVISION = "0001_consolidated_schema"


def rendered_upgrade() -> str:
    operations: list[ops.MigrateOperation] = []
    type_bound_constraint_names: set[str] = set()
    for table in Base.metadata.sorted_tables:
        type_bound_constraint_names.update(
            constraint.name
            for constraint in table.constraints
            if getattr(constraint, "_type_bound", False) and constraint.name
        )
        create = ops.CreateTableOp.from_table(table)
        # Enum(..., native_enum=False, create_constraint=True) recreates its
        # check constraint from the column type.  Keeping SQLAlchemy's internal
        # type-bound CheckConstraint as well would render it twice.
        create.columns = [
            item for item in create.columns if not getattr(item, "_type_bound", False)
        ]
        operations.append(create)
        operations.extend(
            ops.CreateIndexOp.from_index(index)
            for index in sorted(table.indexes, key=lambda value: value.name or "")
        )
    context = MigrationContext.configure(
        dialect_name="postgresql",
        opts={
            "sqlalchemy_module_prefix": "sa.",
            "alembic_module_prefix": "op.",
            "user_module_prefix": None,
        },
    )
    rendered = render_python_code(
        ops.UpgradeOps(ops=operations), migration_context=context
    )
    rendered = rendered.replace(
        "# ### commands auto generated by Alembic - please adjust! ###\n", ""
    ).replace("    # ### end Alembic commands ###\n", "")
    # Alembic renders the Enum-generated CheckConstraint explicitly even after
    # it has been removed from CreateTableOp.  Keeping that line would cause
    # op.create_table() to receive one explicit check while the Enum column
    # creates another check with the same name.
    return "\n".join(
        line
        for line in rendered.splitlines()
        if not (
            "sa.CheckConstraint(" in line
            and any(f"name='{name}'" in line for name in type_bound_constraint_names)
        )
    ) + "\n"


def rendered_downgrade() -> str:
    lines = [
        f"    op.drop_table({table.name!r})"
        for table in reversed(Base.metadata.sorted_tables)
    ]
    return "\n".join(lines) + "\n"


def migration_source() -> str:
    return f'''"""consolidated Visa Automatic schema baseline

Revision ID: {REVISION}
Revises: none
Create Date: 2026-10-13

This file is an immutable schema snapshot.  It deliberately does not import
the application ORM metadata.
"""
from collections.abc import Sequence

from alembic import op
import sqlalchemy as sa
from sqlalchemy.dialects import postgresql


revision: str = "{REVISION}"
down_revision: str | None = None
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None


def upgrade() -> None:
{rendered_upgrade()}


def downgrade() -> None:
{rendered_downgrade()}'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(migration_source(), encoding="utf-8")


if __name__ == "__main__":
    main()
